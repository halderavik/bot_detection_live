"""
Add live bot and fraud tracking to a Decipher survey XML.

What goes into the survey:

- the tracker script (``app/assets/live_quality_tracker.js``) as a
  ``respview.client.js`` style with ``mode="after"``, so it adds to the survey's
  own page scripts instead of replacing them;
- a hidden results page at the end with ``QOS_*`` text questions the tracker fills
  with the respondent id, session id, verdict, score, and risk, so they reach the
  Decipher data file;
- optionally a short privacy notice at the top of the first page;
- optionally an in-survey bot check: a hidden ``QOS_EARLY`` question on a page
  every respondent reaches and a termination that reads it.

Nothing else in the file changes. :func:`remove_tracking` takes the added pieces
out again byte for byte, so tracked XML can be re-tracked without doubling.

Compatibility: other survey builders that write the same ``QOS_*`` pieces (the
Quant OS builder's marker is listed in ``_MARKERS``) are recognised, so a survey
tracked elsewhere is re-tracked here instead of being tracked twice. Nothing here
depends on those tools.
"""


import React, { useEffect, useRef, useState } from 'react';
import { Link } from 'react-router-dom';
import {
  Upload,
  FileCode,
  Download,
  CheckCircle,
  AlertTriangle,
  BarChart3,
  RotateCcw,
  ShieldCheck,
} from 'lucide-react';
import { toast } from 'react-toastify';
import { trackingService } from '../services/apiService';
import { CheckReport, FixResult, FixWithAi, XmlChecklist } from './tracking/XmlCheck';
import DecipherUploadPanel from './tracking/DecipherUploadPanel';

const FALLBACK_SIGNALS = [
  { code: 'automation', label: 'Automated or headless browser' },
  { code: 'scripted_input', label: 'Clicks and key presses generated by script' },
  { code: 'no_input', label: 'Pages answered with no mouse or keyboard use' },
  { code: 'honeypot', label: 'Hidden honeypot field filled in' },
  { code: 'untyped_answers', label: 'Open ends that appeared without typing' },
  { code: 'robotic_timing', label: 'Typing or mouse movement with machine-exact timing' },
];

const errorMessage = (err) => {
  const detail = err?.response?.data?.detail;
  if (typeof detail === 'string') return detail;
  if (Array.isArray(detail)) return detail.map((d) => d.msg).join('; ');
  if (detail && typeof detail.message === 'string') return detail.message;
  return err?.message || 'The upload failed.';
};

const downloadXml = (xml, filename) => {
  const blob = new Blob([xml], { type: 'application/xml;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
};

const SurveyTracking = () => {
  const fileInput = useRef(null);
  const [file, setFile] = useState(null);
  const [surveyId, setSurveyId] = useState('');
  const [terminate, setTerminate] = useState(false);
  const [afterPage, setAfterPage] = useState(2);
  const [signals, setSignals] = useState(FALLBACK_SIGNALS);
  const [chosenSignals, setChosenSignals] = useState(FALLBACK_SIGNALS.map((s) => s.code));
  const [privacyNotice, setPrivacyNotice] = useState(true);
  const [privacyText, setPrivacyText] = useState('');
  const [defaultPrivacy, setDefaultPrivacy] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState(null);
  const [result, setResult] = useState(null);
  // The automatic check of the chosen file, and Fix with AI
  const [check, setCheck] = useState({ status: 'idle', report: null, error: null });
  const [fix, setFix] = useState(null);
  const [fixBusy, setFixBusy] = useState(false);
  const [fixError, setFixError] = useState(null);
  // True when the current file came from Fix with AI; only then may Decipher's errors be fixed with AI.
  const [aiFixed, setAiFixed] = useState(false);

  const runCheck = async (chosen) => {
    setCheck({ status: 'loading', report: null, error: null });
    try {
      const report = await trackingService.checkDecipherXml(chosen);
      setCheck({ status: 'done', report, error: null });
    } catch (err) {
      setCheck({ status: 'error', report: null, error: errorMessage(err) });
    }
  };

  const chooseFile = (chosen, fromAi = false) => {
    setAiFixed(Boolean(chosen && fromAi));
    setFile(chosen || null);
    setResult(null);
    setError(null);
    setFix(null);
    setFixError(null);
    if (chosen) runCheck(chosen);
    else setCheck({ status: 'idle', report: null, error: null });
  };

  const reupload = () => {
    if (fileInput.current) {
      fileInput.current.value = '';
      fileInput.current.click();
    }
  };

  const fixWithAi = async (instructions) => {
    if (!file) return;
    setFixBusy(true);
    setFixError(null);
    setFix(null);
    try {
      setFix(await trackingService.fixDecipherXml(file, instructions));
    } catch (err) {
      setFixError(errorMessage(err));
    } finally {
      setFixBusy(false);
    }
  };

  const useFixed = () => {
    if (!fix) return;
    chooseFile(new File([fix.xml], fix.filename, { type: 'application/xml' }), true);
  };

  const trackingOptions = (id) => ({
    surveyId: id,
    terminate,
    afterPage,
    signals: terminate ? chosenSignals : [],
    privacyNotice,
    privacyText: privacyText.trim(),
  });

  // Decipher refused an AI-fixed file: fix it with Decipher's errors, check it, and add tracking
  // again with the same settings and survey id. The upload panel then sends it to the same survey.
  const retryAfterDecipher = async (decipherErrors, instructions, setStep) => {
    const fixed = await trackingService.fixDecipherXml(file, instructions, decipherErrors);
    if (!fixed.changed) {
      const left = fixed.cannot_fix?.length ? ` ${fixed.cannot_fix.join(' ')}` : '';
      throw new Error(`Fix with AI found nothing it could change for these errors.${left}`);
    }
    const fixedFile = new File([fixed.xml], fixed.filename, { type: 'application/xml' });
    setStep('Checking the fixed file…');
    const report = await trackingService.checkDecipherXml(fixedFile);
    setFile(fixedFile);
    setFix(fixed);
    setCheck({ status: 'done', report, error: null });
    if (!report.ok) throw new Error('The fixed file still has problems; they are listed above.');
    setStep('Adding tracking again…');
    const tracked = await trackingService.addDecipherTracking(fixedFile, trackingOptions(result.survey_id));
    setResult(tracked);
    return { result: tracked, fix: fixed };
  };

  const hasErrors = check.status === 'done' && check.report && !check.report.ok;

  useEffect(() => {
    trackingService
      .getDecipherOptions()
      .then((options) => {
        if (options.signals?.length) {
          setSignals(options.signals);
          setChosenSignals(options.signals.map((s) => s.code));
        }
        setDefaultPrivacy(options.default_privacy_text || '');
        setAfterPage(options.default_after_page || 2);
      })
      .catch(() => {});
  }, []);

  const toggleSignal = (code) => {
    setChosenSignals((current) =>
      current.includes(code) ? current.filter((c) => c !== code) : [...current, code]
    );
  };

  const reset = () => {
    chooseFile(null);
    if (fileInput.current) fileInput.current.value = '';
  };

  const submit = async (event) => {
    event.preventDefault();
    if (!file) return;
    setBusy(true);
    setError(null);
    setResult(null);
    try {
      const response = await trackingService.addDecipherTracking(file, trackingOptions(surveyId.trim()));
      setResult(response);
      toast.success(`Tracking added to ${file.name}`);
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setBusy(false);
    }
  };

  const card = 'bg-white rounded-xl border border-gray-200 shadow-sm border border-gray-200 p-6';
  const label = 'block text-sm font-medium text-gray-700';
  const hint = 'text-xs text-gray-500 mt-1';
  const input =
    'mt-1 block w-full rounded-md border border-gray-300 bg-white ' +
    'text-gray-900 px-3 py-2 text-sm focus:outline-none focus:ring-2 focus:ring-blue-500';

  return (
    <div className="max-w-4xl mx-auto space-y-6">
      <div>
        <h1 className="text-2xl font-semibold tracking-tight text-gray-900">Add tracking to a Decipher survey</h1>
        <p className="text-sm text-gray-600 mt-1">
          Upload the survey XML exported from Decipher. You get back the same survey with live bot and fraud
          tracking added, ready to import into Decipher. Responses appear on that survey&apos;s dashboard here.
        </p>
      </div>

      <XmlChecklist />

      <form onSubmit={submit} className={`${card} space-y-6`} aria-label="Upload a Decipher survey XML">
        <div>
          <label htmlFor="survey-xml" className={label}>Survey XML</label>
          <div
            className="mt-1 flex items-center gap-3 rounded-md border-2 border-dashed border-gray-300 p-4"
            onDragOver={(e) => e.preventDefault()}
            onDrop={(e) => {
              e.preventDefault();
              const dropped = e.dataTransfer.files?.[0];
              if (dropped) chooseFile(dropped);
            }}
          >
            <FileCode className="h-8 w-8 text-gray-400 flex-shrink-0" aria-hidden="true" />
            <div className="flex-1 min-w-0">
              <input
                id="survey-xml"
                ref={fileInput}
                type="file"
                accept=".xml,.txt,application/xml,text/xml"
                onChange={(e) => chooseFile(e.target.files?.[0] || null)}
                className="block w-full text-sm text-gray-700 file:mr-3 file:rounded file:border-0 file:bg-blue-50 file:px-3 file:py-2 file:text-blue-700"
              />
              <p className={hint}>A .xml file (or .txt holding the XML), up to 5 MB. Or drop it here.</p>
              {file && <p className="mt-1 text-xs text-gray-700">Current file: <span className="font-mono">{file.name}</span></p>}
            </div>
          </div>
        </div>

        {check.status === 'loading' && <p className="text-sm text-gray-600" role="status">Checking {file?.name}…</p>}
        {check.status === 'error' && (
          <p className="text-sm text-amber-800" role="status">The file could not be checked ({check.error}). You can still try Add tracking.</p>
        )}
        {check.status === 'done' && check.report && (
          <div className="space-y-4 rounded-lg border border-gray-200 bg-gray-50/60 p-4">
            <CheckReport filename={file?.name || check.report.filename} report={check.report} />
            {check.report.issues.length > 0 && (
              <FixWithAi
                aiAvailable={check.report.ai_available}
                busy={fixBusy}
                onFix={fixWithAi}
                onReupload={reupload}
                report={check.report}
              />
            )}
            {fixError && (
              <div role="alert" className="flex items-start gap-2 rounded-md bg-red-50 border border-red-200 p-3 text-sm text-red-800">
                <AlertTriangle className="h-5 w-5 flex-shrink-0" aria-hidden="true" />
                <span>{fixError}</span>
              </div>
            )}
            {fix && <FixResult fix={fix} onDownload={() => downloadXml(fix.xml, fix.filename)} onUse={useFixed} />}
          </div>
        )}

        <div>
          <label htmlFor="survey-id" className={label}>Survey id (optional)</label>
          <input
            id="survey-id"
            type="text"
            value={surveyId}
            maxLength={100}
            onChange={(e) => setSurveyId(e.target.value)}
            placeholder="Taken from the survey title"
            className={input}
          />
          <p className={hint}>
            Groups this survey&apos;s responses on the dashboard. Re-uploading a tracked file keeps its id unless you
            enter a different one.
          </p>
        </div>

        <fieldset className="space-y-3">
          <legend className={label}>Options</legend>
          <label className="flex items-start gap-3">
            <input
              type="checkbox"
              checked={privacyNotice}
              onChange={(e) => setPrivacyNotice(e.target.checked)}
              className="mt-1 h-4 w-4"
            />
            <span>
              <span className="text-sm text-gray-900">Show a privacy notice on the first page</span>
              <span className={`block ${hint}`}>Tells respondents that the survey checks how answers are entered.</span>
            </span>
          </label>
          {privacyNotice && (
            <div className="ml-7">
              <label htmlFor="privacy-text" className="sr-only">Privacy notice text</label>
              <textarea
                id="privacy-text"
                rows={2}
                maxLength={400}
                value={privacyText}
                onChange={(e) => setPrivacyText(e.target.value)}
                placeholder={defaultPrivacy || 'Default notice'}
                className={input}
              />
              <p className={hint}>Leave empty for the default wording. No $ or square brackets.</p>
            </div>
          )}

          <label className="flex items-start gap-3">
            <input
              type="checkbox"
              checked={terminate}
              onChange={(e) => setTerminate(e.target.checked)}
              className="mt-1 h-4 w-4"
            />
            <span>
              <span className="text-sm text-gray-900">End the survey on a clear bot signal</span>
              <span className={`block ${hint}`}>
                Off by default. A score alone never ends the survey; only the signals ticked below do. If the
                check can&apos;t reach the service, the respondent carries on.
              </span>
            </span>
          </label>
          {terminate && (
            <div className="ml-7 space-y-3">
              <div>
                <label htmlFor="after-page" className="text-sm text-gray-700">Check when page</label>{' '}
                <input
                  id="after-page"
                  type="number"
                  min={1}
                  max={50}
                  value={afterPage}
                  onChange={(e) => setAfterPage(Math.max(1, Math.min(50, Number(e.target.value) || 1)))}
                  className="w-16 rounded-md border border-gray-300 bg-white text-gray-900 px-2 py-1 text-sm"
                />{' '}
                <span className="text-sm text-gray-700">is submitted</span>
                <p className={hint}>Only page breaks every respondent reaches count (not inside loops or conditional blocks).</p>
              </div>
              <div className="space-y-1">
                {signals.map((signal) => (
                  <label key={signal.code} className="flex items-center gap-2 text-sm text-gray-800">
                    <input
                      type="checkbox"
                      checked={chosenSignals.includes(signal.code)}
                      onChange={() => toggleSignal(signal.code)}
                      className="h-4 w-4"
                    />
                    {signal.label}
                  </label>
                ))}
              </div>
            </div>
          )}
        </fieldset>

        {error && (
          <div role="alert" className="flex items-start gap-2 rounded-md bg-red-50 border border-red-200 p-3 text-sm text-red-800">
            <AlertTriangle className="h-5 w-5 flex-shrink-0" aria-hidden="true" />
            <span>{error}</span>
          </div>
        )}

        <div className="flex items-center gap-3">
          <button
            type="submit"
            disabled={!file || busy || check.status === 'loading' || hasErrors || (terminate && chosenSignals.length === 0)}
            className="inline-flex items-center gap-2 rounded-md bg-blue-600 px-4 py-2 text-sm font-medium text-white hover:bg-blue-700 disabled:opacity-50 disabled:cursor-not-allowed focus:outline-none focus:ring-2 focus:ring-blue-500"
          >
            <Upload className="h-4 w-4" aria-hidden="true" />
            {busy ? 'Adding tracking…' : 'Add tracking'}
          </button>
          {hasErrors && <span className="text-sm text-red-700">Fix the problems above first.</span>}
          {(file || result) && (
            <button type="button" onClick={reset} className="inline-flex items-center gap-1 text-sm text-gray-600 hover:underline">
              <RotateCcw className="h-4 w-4" aria-hidden="true" /> Start over
            </button>
          )}
        </div>
      </form>

      {result && (
        <section className={`${card} space-y-5`} aria-label="Tracking added">
          <div className="flex items-start gap-3">
            <CheckCircle className="h-6 w-6 text-green-600 flex-shrink-0" aria-hidden="true" />
            <div>
              <h2 className="text-base font-semibold text-gray-900">
                {result.replaced_existing_tracking ? 'Tracking updated' : 'Tracking added'}
              </h2>
              <p className="text-sm text-gray-600">
                Survey id <span className="font-mono font-medium text-gray-900">{result.survey_id}</span>
                {' · '}{result.survey.questions} questions, {result.survey.pages} pages
                {result.survey.loops ? `, ${result.survey.loops} loop(s)` : ''}
                {result.survey.blocks ? `, ${result.survey.blocks} block(s)` : ''}
              </p>
              {result.replaced_existing_tracking && (
                <p className="text-sm text-sm text-gray-600 mt-1">
                  The file already had tracking; it was replaced with these settings, not added twice.
                </p>
              )}
              {result.existing_sessions > 0 && (
                <p className="text-sm text-sm text-gray-600 mt-1">
                  This survey id already has {result.existing_sessions} session(s); new responses join them.
                </p>
              )}
            </div>
          </div>

          <div>
            <h3 className="text-sm font-medium text-gray-900">What was added</h3>
            <ul className="mt-2 list-disc pl-5 space-y-1 text-sm text-gray-700">
              {result.added.map((item) => <li key={item}>{item}</li>)}
            </ul>
            <p className="text-sm text-gray-600 mt-2 flex items-center gap-1">
              <ShieldCheck className="h-4 w-4" aria-hidden="true" />
              {result.signed ? 'Signed: only this survey\'s tracker can add sessions to it. ' : ''}
              Tracker calls <span className="font-mono">{result.api_base}</span>
            </p>
          </div>

          {result.warnings?.length > 0 && (
            <div className="rounded-md bg-amber-50 border border-amber-200 p-3">
              <ul className="space-y-1 text-sm text-amber-800">
                {result.warnings.map((w) => (
                  <li key={w} className="flex gap-2"><AlertTriangle className="h-4 w-4 flex-shrink-0 mt-0.5" aria-hidden="true" />{w}</li>
                ))}
              </ul>
            </div>
          )}

          <div className="flex flex-wrap items-center gap-3">
            <button
              type="button"
              onClick={() => downloadXml(result.xml, result.filename)}
              className="inline-flex items-center gap-2 rounded-md bg-blue-600 px-4 py-2 text-sm font-medium text-white hover:bg-blue-700 focus:outline-none focus:ring-2 focus:ring-blue-500"
            >
              <Download className="h-4 w-4" aria-hidden="true" /> Download {result.filename}
            </button>
            <Link
              to={`/surveys/${encodeURIComponent(result.survey_id)}`}
              className="inline-flex items-center gap-2 rounded-md border border-gray-300 px-4 py-2 text-sm font-medium text-gray-800 hover:bg-gray-50"
            >
              <BarChart3 className="h-4 w-4" aria-hidden="true" /> Open the survey dashboard
            </Link>
            <Link
              to={`/quality?survey=${encodeURIComponent(result.survey_id)}`}
              className="inline-flex items-center gap-2 rounded-md border border-gray-300 px-4 py-2 text-sm font-medium text-gray-800 hover:bg-gray-50"
            >
              <ShieldCheck className="h-4 w-4" aria-hidden="true" /> Live quality and rules
            </Link>
          </div>

          <DecipherUploadPanel aiFixed={aiFixed} key={result.survey_id} onAiRetry={retryAfterDecipher} result={result} />

          <div className="text-sm text-gray-600">
            <h3 className="font-medium text-gray-900">Next</h3>
            <ol className="mt-1 list-decimal pl-5 space-y-1">
              <li>
                {result.decipher_upload?.configured
                  ? 'Upload to Decipher above, or download the file and replace the XML in Decipher’s XML editor.'
                  : 'In Decipher, open the survey’s XML editor, replace the XML with the downloaded file, and save.'}
              </li>
              <li>Test the survey. Its sessions appear on the dashboard within a few seconds.</li>
              <li>The hidden {result.hidden_fields.join(', ')} questions carry each respondent&apos;s result into the Decipher data.</li>
            </ol>
          </div>
        </section>
      )}
    </div>
  );
};

export default SurveyTracking;

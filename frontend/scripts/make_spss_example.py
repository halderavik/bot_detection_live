"""
Build the example quality-check data files shown on the "Data & SPSS" page.

Writes to frontend/public/examples/:
  qos_example.sav   SPSS file laid out like a Decipher export of a tracked survey
  qos_example.csv   the same rows as CSV
  qos_labels.sps    SPSS syntax: value labels, a numeric score, and one 0/1 variable per reason

Every respondent is made up. Variable names, types and titles follow
backend/app/services/decipher_tracking.py (_TEXT_FIELDS, _NUMBER_FIELDS, _LIST_FIELDS);
reason codes follow backend/app/services/quality_variables.py (REASON_CODES).

usage (from backend/.venv): python frontend/scripts/make_spss_example.py
"""
from pathlib import Path

import pandas as pd
import pyreadstat

OUT = Path(__file__).resolve().parents[1] / "public" / "examples"

TITLES = {
    "record": "Record number",
    "uuid": "Participant identifier",
    "date": "Completion time and date",
    "status": "Participant status",
    "Q1": "Q1: Overall, how satisfied are you with your coffee machine?",
    "Q2": "Q2: Why do you say that?",
    "QOS_RESPONDENT": "Quality check respondent id (leave blank)",
    "QOS_SESSION": "Quality check session id (leave blank)",
    "QOS_FLAG": "Quality check result (leave blank)",
    "QOS_SCORE": "Quality check score (leave blank)",
    "QOS_RISK": "Quality check risk level (leave blank)",
    "QOS_STATUS": "Quality status: 1 human, 2 suspect, 3 bot (leave blank)",
    "QOS_BEHAV": "Behaviour bot score 0-100 (higher is worse) (leave blank)",
    "QOS_OES": "Open-ended answer quality 0-100 (higher is better) (leave blank)",
    "QOS_FRAUD": "Fraud score 0-100 (higher is worse) (leave blank)",
    "QOS_DUP": "Duplicate respondent: 1 yes, 0 no (leave blank)",
    "QOS_DUP_SCORE": "Duplicate score 0-100 (higher is worse) (leave blank)",
    "QOS_IP_RISK": "IP address risk 0-100 (leave blank)",
    "QOS_DEVICE_RISK": "Device reuse risk 0-100 (leave blank)",
    "QOS_GEO_RISK": "Location mismatch risk 0-100 (leave blank)",
    "QOS_VELOCITY": "Survey-taking velocity risk 0-100 (leave blank)",
    "QOS_DATACENTER": "Data centre, VPN or proxy IP: 1 yes, 0 no (leave blank)",
    "QOS_SPEEDER": "Pages answered too fast (leave blank)",
    "QOS_STRAIGHTLINE": "Straight-lined grid questions (leave blank)",
    "QOS_FLAGCOUNT": "Number of quality reasons (leave blank)",
    "QOS_REASON": "Main quality reason code (0 none) (leave blank)",
    "QOS_REASONS": "All quality reason codes (leave blank)",
}
TEXT = {"uuid", "date", "Q2", "QOS_RESPONDENT", "QOS_SESSION", "QOS_FLAG", "QOS_SCORE", "QOS_RISK", "QOS_REASONS"}

REASONS = {
    0: "None", 1: "Automated or headless browser", 2: "Clicks and key presses generated by script",
    3: "Pages answered with no mouse or keyboard use", 4: "Hidden honeypot field filled in",
    5: "Open ends that appeared without typing", 6: "Bot-like behaviour score",
    7: "Typing or mouse movement with machine-exact timing", 8: "Page times longer than the time the server saw",
    10: "Data centre, VPN or proxy IP address", 11: "Same device seen on other sessions of this survey",
    12: "Same IP address used repeatedly", 13: "Answers copied from another respondent",
    14: "Many surveys started in a short time", 15: "Same respondent seen from different countries within an hour",
    20: "Low-quality open-ended answers", 21: "Straight-lined grid questions", 22: "Questions answered too fast",
}

N = None  # blank (system-missing) in SPSS
# uuid, Q1, Q2, flag, score, risk, status, behav, oes, fraud, dup, dupscore, ip, device, geo, velocity, dc, speeder, straight, reasons
ROWS = [
    ("k3f9x2m7q1", 4, "It makes good coffee quickly and the milk frother is easy to clean.", "human", "0.08", "low", 1, 12, 88, 6, 0, N, 5, 0, 0, 3, 0, 0, 0, []),
    ("p8d2w5r4t6", 5, "Reliable every morning, never had a problem in two years.", "human", "0.15", "low", 1, 21, 82, 10, 0, N, 10, 0, 0, 5, 0, 0, 0, []),
    ("b7n4c1v9z3", 3, "ok", "human", "0.34", "medium", 2, 18, 22, 8, 0, N, 5, 0, 0, 3, 0, 3, 1, [20, 21, 22]),
    ("h2j6l8s0a5", 5, "The machine is good and I like the coffee it makes every day.", "bot", "0.95", "critical", 3, 95, 40, 12, 0, N, 5, 0, 0, 3, 0, 0, 0, [1, 7]),
    ("e5r7y9u1i3", 5, "Reliable every morning, never had a problem in two years.", "human", "0.48", "medium", 2, 20, 30, 61, 1, 100, 40, 100, 0, 10, 0, 0, 0, [11, 13]),
    ("m1q3e5t7u9", 4, "Great taste, a bit noisy when grinding beans.", "bot", "0.85", "high", 3, 85, 75, 55, 0, N, 100, 0, 0, 3, 1, 0, 0, [4, 10]),
    ("g4h6j8k0l2", 2, "Too slow to heat up, and descaling is a hassle.", "human", "0.11", "low", 1, 14, N, 7, 0, N, 5, 0, 0, 3, 0, 0, 0, []),
    ("w9e1r3t5y7", 4, "Nice design.", "unknown", N, "", N, N, N, N, N, N, N, N, N, N, N, N, N, None),
]


def build() -> pd.DataFrame:
    records = []
    for i, (uuid, q1, q2, flag, score, risk, status, behav, oes, fraud, dup, dupscore, ip, device, geo, vel, dc,
            speed, straight, reasons) in enumerate(ROWS, start=1):
        unknown = reasons is None
        reasons = reasons or []
        records.append({
            "record": i, "uuid": uuid, "date": f"11/2{i}/2026 1{i}:0{i}", "status": 3, "Q1": q1, "Q2": q2,
            "QOS_RESPONDENT": uuid, "QOS_SESSION": "" if unknown else f"6f1c2a9e-{i:04d}-4b7d-9a31-5e2f8c0d{i:04d}",
            "QOS_FLAG": flag, "QOS_SCORE": score or "", "QOS_RISK": risk,
            "QOS_STATUS": status, "QOS_BEHAV": behav, "QOS_OES": oes, "QOS_FRAUD": fraud, "QOS_DUP": dup,
            "QOS_DUP_SCORE": dupscore, "QOS_IP_RISK": ip, "QOS_DEVICE_RISK": device, "QOS_GEO_RISK": geo,
            "QOS_VELOCITY": vel, "QOS_DATACENTER": dc, "QOS_SPEEDER": speed, "QOS_STRAIGHTLINE": straight,
            "QOS_FLAGCOUNT": N if unknown else len(reasons), "QOS_REASON": N if unknown else (reasons[0] if reasons else 0),
            "QOS_REASONS": ",".join(str(r) for r in reasons),
        })
    frame = pd.DataFrame(records, columns=list(TITLES))
    for name in TITLES:
        if name not in TEXT:
            frame[name] = pd.to_numeric(frame[name], errors="coerce").astype("float64")
    return frame


def syntax() -> str:
    reason_labels = "\n".join(f"   {code} '{label}'" for code, label in REASONS.items())
    dummies = "\n".join(
        f"COMPUTE QOS_R{code} = CHAR.INDEX(CONCAT(',', RTRIM(QOS_REASONS), ','), ',{code},') > 0.\n"
        f"VARIABLE LABELS QOS_R{code} 'Reason {code}: {label}'."
        for code, label in REASONS.items() if code
    )
    return f"""* Quality check variables from the bot-detection service (QOS_*).
* Run on a Decipher SPSS export of a tracked survey. Safe to run more than once.
* Blank QOS values are system-missing: the respondent did not reach the last page,
* the check did not apply, or the service did not answer in time (QOS_FLAG = 'unknown').

VALUE LABELS QOS_STATUS 1 'Human' 2 'Suspect' 3 'Bot'
 /QOS_DUP QOS_DATACENTER 0 'No' 1 'Yes'
 /QOS_REASON
{reason_labels}.

* QOS_SCORE arrives as text (0 to 1); this makes a numeric copy.
COMPUTE QOS_SCORE_N = NUMBER(QOS_SCORE, F8.4).
VARIABLE LABELS QOS_SCORE_N 'Quality check score 0-1 (numeric)'.
FORMATS QOS_SCORE_N (F6.2).

* One 0/1 variable per reason code, from the comma-separated QOS_REASONS.
{dummies}
FORMATS QOS_R1 TO QOS_R22 (F1.0).
VALUE LABELS QOS_R1 TO QOS_R22 0 'No' 1 'Yes'.

* Suggested cleaning flag: keep humans, review suspects, remove bots.
RECODE QOS_STATUS (1=1) (2=2) (3=3) (SYSMIS=9) INTO QOS_ACTION.
VARIABLE LABELS QOS_ACTION 'Suggested action'.
VALUE LABELS QOS_ACTION 1 'Keep' 2 'Review' 3 'Remove' 9 'Not checked - see dashboard'.
FORMATS QOS_ACTION (F1.0).

FREQUENCIES QOS_STATUS QOS_FLAG QOS_REASON QOS_ACTION.
EXECUTE.
"""


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    frame = build()
    pyreadstat.write_sav(frame, OUT / "qos_example.sav", column_labels=TITLES,
                         variable_value_labels={"status": {3: "Qualified"}})
    frame.to_csv(OUT / "qos_example.csv", index=False, encoding="utf-8-sig", float_format="%g")
    (OUT / "qos_labels.sps").write_text(syntax(), encoding="utf-8")
    back, meta = pyreadstat.read_sav(OUT / "qos_example.sav")
    print(f"{len(back)} rows, {len(meta.column_names)} variables")
    print(back[["uuid", "QOS_FLAG", "QOS_SCORE", "QOS_STATUS", "QOS_REASON", "QOS_REASONS"]].to_string())


if __name__ == "__main__":
    main()
